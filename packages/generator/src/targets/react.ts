import type { SdkTarget } from "../types.js";
import { hookNameFromMethod, ZERO_ARG_READ_METHODS } from "../shared/reads.js";

function renderReactHooks(): string {
  const hooks = ZERO_ARG_READ_METHODS.map((method) => {
    const hookName = hookNameFromMethod(method);
    return `export function ${hookName}(client: StationClient) {
  return useStationQuery(client, "${method}", () => client.${method}());
}`;
  }).join("\n\n");

  return `/** Generated by @rivi-software/radiotools-sdk-generator — do not edit by hand. */
import { useCallback, useEffect, useRef, useState } from "react";
import type { StationClient } from "@rivi-software/radiotools-sdk";

type QueryState<T> = {
  data: T | undefined;
  error: Error | undefined;
  loading: boolean;
  refresh: () => void;
};

function useStationQuery<T>(
  client: StationClient,
  method: string,
  read: () => Promise<T>,
): QueryState<T> {
  const [data, setData] = useState<T | undefined>(undefined);
  const [error, setError] = useState<Error | undefined>(undefined);
  const [loading, setLoading] = useState(true);
  // Each render passes a new \`read\` arrow; keep the latest in a ref so it does not restart the query.
  const readRef = useRef(read);
  // Bumped by every request and on cleanup: only the newest request may write state.
  const generation = useRef(0);

  useEffect(() => {
    readRef.current = read;
  });

  const refresh = useCallback(() => {
    const request = ++generation.current;
    setLoading(true);
    void readRef
      .current()
      .then((value) => {
        if (request !== generation.current) return;
        setData(value);
        setError(undefined);
      })
      .catch((cause: unknown) => {
        if (request !== generation.current) return;
        setError(cause instanceof Error ? cause : new Error(String(cause)));
      })
      .finally(() => {
        if (request === generation.current) setLoading(false);
      });
  }, []);

  useEffect(() => {
    refresh();
    return () => {
      generation.current += 1;
    };
  }, [client, method, refresh]);

  return { data, error, loading, refresh };
}

export function useRecommendedPollInterval(client: StationClient): QueryState<number> {
  return useStationQuery(client, "recommendedPollIntervalMs", () =>
    client.recommendedPollIntervalMs(),
  );
}

${hooks}
`;
}

export const reactTarget: SdkTarget = {
  id: "react",
  description: "React hooks wrapping @rivi-software/radiotools-sdk (packages/sdk-react)",
  outputDir: (repoRoot) => `${repoRoot}/packages/sdk-react/src`,
  generate: () => [
    {
      path: "hooks.generated.ts",
      contents: renderReactHooks(),
    },
    {
      path: "index.ts",
      contents: `export * from "./hooks.generated.js";
`,
    },
  ],
};
